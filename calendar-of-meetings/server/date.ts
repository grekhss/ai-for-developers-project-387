/**
 * Сегодняшняя дата сервера — 'YYYY-MM-DD'. Единственное место в `server/`,
 * читающее системные часы (T3): правила дат принимают момент параметром, и
 * только этот вызов смотрит на календарь. Нужен админскому списку (S4/Q6) —
 * нижней границе «сегодня и позже»; сам репозиторий часы не читает.
 *
 * Локальная зона, а не UTC: `toISOString()` в UTC+3 поздним вечером отдал бы
 * вчерашний день, и прошедшая встреча осталась бы в списке. На фронте ту же
 * роль играет `today()` из `src/lib/date.ts` (через dayjs); сервер собирает
 * строку сам, чтобы не тянуть date-библиотеку ради одной функции.
 */
export function today(): string {
  const now = new Date();
  const month = String(now.getMonth() + 1).padStart(2, '0');
  const day = String(now.getDate()).padStart(2, '0');
  return `${now.getFullYear()}-${month}-${day}`;
}
